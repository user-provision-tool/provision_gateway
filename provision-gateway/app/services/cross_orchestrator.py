"""Grant-driven cross-path orchestration (GRILLING G83).

The gateway owns two derived artifacts:

1. the cross resolver's **dnsmasq** config (one wildcard per service domain
   that has at least one reachable target), written through the shared volume;
2. each granted source's **resolv.conf + cross-network membership**, applied by
   the -api through its asynchronous generic API.

They are refreshed on every grant/lifecycle change and once on the gateway's
own startup (a one-time pass, not a periodic reconcile). A stack rebuild
restarts the gateway, so it converges.
"""

from __future__ import annotations

import asyncio
import logging
import os
import time
from pathlib import Path

from ..config import settings
from ..database import SessionLocal
from . import service_grants
from .provision_service import provision_service

_log = logging.getLogger("gateway.cross_orchestrator")

CONFIG_HEADER = (
    "# Generated by the gateway from the service-grant state (GRILLING G83).\n"
    "# Do not edit: the next grant change or gateway startup rewrites this file.\n"
    "# Only the service-domain wildcards are answered; every other name is\n"
    "# refused by the resolver (no upstream), so the client falls through to the\n"
    "# next nameserver.\n"
)


class CrossOrchestrator:
    def _config_path(self) -> Path:
        return settings.CROSS_CONFIG_DIR / "dnsmasq.d" / "cross.conf"

    def write_dnsmasq_config(self, domains: set[str]) -> bool:
        """Rewrite the resolver config atomically; True when the content changed.

        Every wildcard points at the cross nginx's cross-network IP. The file is
        a directory mount (not a single-file mount) so an atomic replace is seen
        by the resolver container; its watcher restarts dnsmasq when mtime moves.
        """
        path = self._config_path()
        path.parent.mkdir(parents=True, exist_ok=True)
        lines = [CONFIG_HEADER, "no-resolv\n", "no-hosts\n"]
        for domain in sorted(d for d in domains if d):
            # `local` makes the whole domain local, so an AAAA (or any other
            # type the wildcard does not answer) returns NODATA instead of
            # REFUSED. REFUSED for an IN-ZONE name would make a client treat
            # the name as failing rather than as IPv4-only (measured 2026-11-03).
            lines.append(f"local=/{domain}/\n")
            lines.append(f"address=/*.{domain}/{settings.CROSS_NGINX_IP}\n")
        content = "".join(lines)
        try:
            if path.read_text(encoding="utf-8") == content:
                return False
        except OSError:
            pass
        tmp = path.with_suffix(".tmp")
        tmp.write_text(content, encoding="utf-8")
        os.replace(tmp, path)
        _log.info("cross resolver config written: %d domain(s) (%s)",
                  len(domains), ", ".join(sorted(domains)) or "-")
        return True

    async def _poll_task(self, task_id: str) -> None:
        deadline = time.monotonic() + settings.CROSS_TASK_TIMEOUT_SEC
        while time.monotonic() < deadline:
            data = await provision_service.get_task(task_id)
            status = str(data.get("status") or "")
            if status == "completed":
                return
            if status in ("failed", "cancelled", "unknown"):
                raise RuntimeError(
                    f"the -api task {task_id} ended {status}: {data.get('error') or ''}"
                )
            await asyncio.sleep(0.5)
        raise TimeoutError(f"the -api task {task_id} did not finish in time")

    async def _apply(self, service_id: str, present: bool) -> bool:
        """Submit + poll, with the ruling's timeout/retry."""
        last: Exception | None = None
        for attempt in range(1, settings.CROSS_TASK_RETRIES + 1):
            try:
                if present:
                    data = await provision_service.set_extra_resolver(
                        service_id, resolver_ip=settings.CROSS_RESOLVER_IP,
                        network=settings.CROSS_NETWORK,
                    )
                else:
                    data = await provision_service.clear_extra_resolver(service_id)
                await self._poll_task(str(data["task_id"]))
                return True
            except Exception as exc:  # noqa: BLE001 — retry, then report
                last = exc
                _log.warning(
                    "cross-path update for %s attempt %d/%d failed: %s",
                    service_id, attempt, settings.CROSS_TASK_RETRIES, exc,
                )
                if attempt < settings.CROSS_TASK_RETRIES:
                    await asyncio.sleep(1.0)
        _log.error("cross-path update for %s gave up: %s", service_id, last)
        return False

    async def _sync_source(self, entry: dict) -> bool:
        service_id = str(entry["service_id"])
        try:
            current = await provision_service.get_extra_resolver(service_id)
        except Exception:  # noqa: BLE001 — a stale read is not a reason to skip
            current = {}
        if (current.get("extra_resolver") == settings.CROSS_RESOLVER_IP
                and current.get("extra_network") == settings.CROSS_NETWORK):
            return True
        return await self._apply(service_id, present=True)

    async def _clear_source(self, service_id: str) -> bool:
        return await self._apply(service_id, present=False)

    async def sync_all(self) -> dict:
        """Refresh the resolver config and every source's resolv.conf/membership."""
        db = SessionLocal()
        try:
            domains = service_grants.reachable_domains(db)
            changed = self.write_dnsmasq_config(domains)
            sources = service_grants.sources_with_targets(db)
            entries = service_grants.entries_by_id()
        finally:
            db.close()
        applied = 0
        for service_id in list(sources):
            entry = entries.get(str(service_id))
            if entry is not None and await self._sync_source(entry):
                applied += 1
        # A live service that lost its last target must release the pair. A
        # stopped service keeps it: its containers are re-applied when they
        # start, and its targets may return.
        cleared = 0
        clear_failed = 0
        for service_id, entry in entries.items():
            if str(service_id) in sources or not service_grants.live(entry):
                continue
            try:
                current = await provision_service.get_extra_resolver(str(service_id))
            except Exception:  # noqa: BLE001
                continue
            if current.get("extra_resolver"):
                if await self._clear_source(str(service_id)):
                    cleared += 1
                else:
                    clear_failed += 1
        return {"domains": sorted(domains), "config_changed": changed,
                "sources": len(sources), "applied": applied,
                "failed": len(sources) - applied,
                "cleared": cleared, "clear_failed": clear_failed}

    async def startup_pass(self) -> dict:
        """The gateway's one-time startup pass, retried while the -api boots.

        A stack rebuild starts the gateway and the -api together; the first
        attempts may find the -api mid-migration. The stored fields make the
        -api's own startup pass sufficient for already-configured sources, so
        this retry loop is only needed for the first convergence.
        """
        last: dict = {}
        for attempt in range(1, 13):
            last = await self.sync_all()
            if last.get("failed", 0) == 0 and last.get("clear_failed", 0) == 0:
                return last
            _log.info("cross startup pass attempt %d: %s failed, %s clear-failed; retrying",
                      attempt, last.get("failed"), last.get("clear_failed"))
            await asyncio.sleep(10.0)
        return last

    async def sync_after_task(self, task_id: str) -> None:
        """Wait for a deploy/rebuild task to finish, then refresh everything."""
        try:
            while True:
                data = await provision_service.get_task(task_id)
                if str(data.get("status") or "") in (
                        "completed", "failed", "cancelled", "unknown"):
                    break
                await asyncio.sleep(2.0)
        except Exception:  # noqa: BLE001 — the next change/startup retries
            return
        await self.sync_all()


cross_orchestrator = CrossOrchestrator()


def schedule_sync() -> None:
    """Fire-and-forget refresh from an ASYNC request handler."""
    try:
        loop = asyncio.get_running_loop()
    except RuntimeError:
        return
    loop.create_task(cross_orchestrator.sync_all())


def schedule_sync_threadsafe() -> None:
    """Fire-and-forget refresh from a SYNC route (FastAPI's threadpool).

    There is no running loop in that thread, so the refresh gets its own thread
    and its own event loop; the request reply is never delayed by the -api call.
    """
    import threading

    def _run() -> None:
        try:
            asyncio.run(cross_orchestrator.sync_all())
        except Exception:  # noqa: BLE001 — the next change/startup retries
            _log.exception("cross-path refresh failed")

    threading.Thread(target=_run, name="cross-sync", daemon=True).start()
