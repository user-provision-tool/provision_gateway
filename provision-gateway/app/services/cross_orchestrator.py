"""Grant-driven cross-path orchestration (GRILLING G83).

The gateway owns two derived artifacts:

1. the cross resolver's **dnsmasq** config (one wildcard per service domain
   that has at least one reachable target), written through the shared volume;
2. each granted source's **resolv.conf + cross-network membership**, applied by
   the -api through its asynchronous generic API.

They are refreshed on every grant/lifecycle change, once on the gateway's own
startup, and — since G91 (no static pins) — by a ~5 s address watch that
re-resolves the two dynamic values: a changed cross nginx rewrites the dnsmasq
records, a changed cross resolver triggers the re-apply pass.
"""

from __future__ import annotations

import asyncio
import logging
import os
import time
from pathlib import Path

from ..config import settings
from ..database import SessionLocal
from . import cross_values, service_grants
from .provision_service import provision_service

_log = logging.getLogger("gateway.cross_orchestrator")

# T0/R4 — the targeted-sync outcome keys (the grant route and the UI branch on
# these, never on prose).
OUTCOME_OK = "ok"
OUTCOME_DEFERRED = "deferred"
OUTCOME_ERROR = "error"

CONFIG_HEADER = (
    "# Generated by the gateway from the service-grant state (GRILLING G83).\n"
    "# Do not edit: the next grant change or gateway startup rewrites this file.\n"
    "# Only the service-domain wildcards are answered; every other name is\n"
    "# refused by the resolver (no upstream), so the client falls through to the\n"
    "# next nameserver.\n"
)


class CrossOrchestrator:
    def _config_path(self) -> Path:
        return settings.CROSS_CONFIG_DIR / "dnsmasq.d" / "cross.conf"

    def write_dnsmasq_config(
        self, domains: set[str], *, cross_nginx_ip: str | None = None,
    ) -> bool:
        """Rewrite the resolver config atomically; True when the content changed.

        Every wildcard points at the cross nginx's current **cross-network** IP
        (G91: resolved through the cross-only alias, never a startup constant).
        The file is a directory mount (not a single-file mount) so an atomic
        replace is seen by the resolver container; its watcher restarts dnsmasq
        when mtime moves. A missing value is not written: an empty wildcard
        target would black-hole the whole cross path.
        """
        cross_ip = cross_nginx_ip or cross_values.current_cross_nginx_ip()
        if not cross_ip:
            _log.error("cross nginx address is not resolved; dnsmasq config left as is")
            return False
        path = self._config_path()
        path.parent.mkdir(parents=True, exist_ok=True)
        lines = [CONFIG_HEADER, "no-resolv\n", "no-hosts\n"]
        for domain in sorted(d for d in domains if d):
            # `local` makes the whole domain local, so an AAAA (or any other
            # type the wildcard does not answer) returns NODATA instead of
            # REFUSED. REFUSED for an IN-ZONE name would make a client treat
            # the name as failing rather than as IPv4-only (measured 2026-11-03).
            lines.append(f"local=/{domain}/\n")
            lines.append(f"address=/*.{domain}/{cross_ip}\n")
        content = "".join(lines)
        try:
            if path.read_text(encoding="utf-8") == content:
                return False
        except OSError:
            pass
        tmp = path.with_suffix(".tmp")
        tmp.write_text(content, encoding="utf-8")
        os.replace(tmp, path)
        _log.info("cross resolver config written: %d domain(s) (%s)",
                  len(domains), ", ".join(sorted(domains)) or "-")
        return True

    async def _poll_task(self, task_id: str) -> None:
        """Read the task row directly (R9.2) instead of polling the -api."""
        from . import registry_tasks
        deadline = time.monotonic() + settings.CROSS_TASK_TIMEOUT_SEC
        while time.monotonic() < deadline:
            data = await asyncio.to_thread(registry_tasks.get, task_id) or {}
            status = str(data.get("status") or "")
            if status == "completed":
                return
            if status in ("failed", "cancelled", "unknown"):
                raise RuntimeError(
                    f"the -api task {task_id} ended {status}: {data.get('error') or ''}"
                )
            await asyncio.sleep(0.5)
        raise TimeoutError(f"the -api task {task_id} did not finish in time")

    async def _pair_matches(
        self, service_id: str, present: bool, resolver_name: str | None,
    ) -> bool:
        """The stored pair after a deduplicated task (R4.2/G94).

        Only the dedupe path reads it: the global reconciler compares the one
        entries query instead (R10.3), and the targeted sync owns exactly one
        source.
        """
        try:
            current = await provision_service.get_extra_resolver(service_id)
        except Exception:  # noqa: BLE001 — re-submitting is the safe fallback
            return False
        if not present:
            return not current.get("extra_resolver")
        return (current.get("extra_resolver") == resolver_name
                and current.get("extra_network") == settings.CROSS_NETWORK)

    @staticmethod
    def _outcome(ok: bool, outcome: str, reason: str | None = None) -> dict:
        return {"ok": ok, "outcome": outcome, "reason": reason}

    async def _apply(
        self, service_id: str, present: bool, *, resolver_name: str | None = None,
    ) -> dict:
        """Submit + poll, with the ruling's timeout/retry, and an explicit outcome.

        G92: a queue refusal or a queued-wait timeout DEFERS to the next sync
        cycle instead of retrying. Retrying a refusal submits the same work
        again into a full queue — the feedback loop that saturated the queue on
        the first post-queue startup pass (measured 2026-11-10) — and the queue
        itself has no wait timeout, so a task still queued after the caller's
        30 s is delayed, not failed.

        G94 R4.2: the -api's maintenance in-flight guard may answer with an
        existing task (`deduplicated`). The click polls that task; if the stored
        pair still does not match the desired state, the in-flight row was the
        opposite direction, so one fresh submit follows after it settles.

        Returns ``{"ok": bool, "outcome": "ok"|"deferred"|"error", "reason"}``.
        A deferred/error outcome is NOT a lost grant: the row is durable and the
        next global reconciler pass retries it (R4).
        """
        last: Exception | None = None
        for attempt in range(1, settings.CROSS_TASK_RETRIES + 1):
            try:
                if present:
                    if not resolver_name:
                        return self._outcome(
                            False, OUTCOME_ERROR,
                            "the cross resolver name is not configured")
                    data = await provision_service.set_extra_resolver(
                        service_id, resolver_name=resolver_name,
                        network=settings.CROSS_NETWORK,
                    )
                else:
                    data = await provision_service.clear_extra_resolver(service_id)
                task_id = str(data.get("task_id") or "")
                await self._poll_task(str(data["task_id"]))
                if data.get("deduplicated"):
                    if await self._pair_matches(service_id, present, resolver_name):
                        out = self._outcome(True, OUTCOME_OK)
                        out["task_id"] = task_id
                        return out
                    _log.info(
                        "deduplicated update for %s settled; the pair still "
                        "differs, submitting the desired direction", service_id)
                    continue
                out = self._outcome(True, OUTCOME_OK)
                out["task_id"] = task_id
                return out
            except TimeoutError as exc:
                _log.info(
                    "cross-path update for %s is still queued; deferring to the "
                    "next sync cycle", service_id)
                last = exc
                return self._outcome(
                    False, OUTCOME_DEFERRED,
                    "the update is still queued; the next sync cycle retries it")
            except Exception as exc:  # noqa: BLE001 — retry, then report
                last = exc
                code = _refusal_code(exc)
                if code in ("queue_full", "queue_unavailable"):
                    _log.info(
                        "cross-path update for %s deferred: %s", service_id, code)
                    return self._outcome(
                        False, OUTCOME_DEFERRED,
                        f"the task queue refused the update ({code}); the next "
                        "sync cycle retries it")
                _log.warning(
                    "cross-path update for %s attempt %d/%d failed: %s",
                    service_id, attempt, settings.CROSS_TASK_RETRIES, exc,
                )
                if attempt < settings.CROSS_TASK_RETRIES:
                    await asyncio.sleep(1.0)
        _log.error("cross-path update for %s gave up: %s", service_id, last)
        return self._outcome(False, OUTCOME_ERROR, str(last) if last else "unknown error")

    async def _sync_source(self, entry: dict, *, resolver_name: str) -> dict:
        """Compare the STORED pair from the entries query; submit only if stale.

        No per-source HTTP GET: the global reconciler reads the pairs in the
        same one query that produced the entries (R10.3). A source with no
        instance carries no pair to apply — that is a no-op, not an error.
        """
        service_id = str(entry["service_id"])
        if entry.get("status") is None:
            return self._outcome(True, OUTCOME_OK, "the source has no instance")
        if (entry.get("extra_resolver") == resolver_name
                and entry.get("extra_network") == settings.CROSS_NETWORK):
            return self._outcome(True, OUTCOME_OK)
        return await self._apply(service_id, present=True, resolver_name=resolver_name)

    async def _clear_source(self, entry: dict) -> dict:
        if not entry.get("extra_resolver"):
            return self._outcome(True, OUTCOME_OK)
        return await self._apply(str(entry["service_id"]), present=False)

    async def sync_all(self) -> dict:
        """The GLOBAL reconciler: every source's resolv.conf/membership.

        Runs only on gateway startup, a cross resolver/nginx address change and
        service lifecycle changes (G94 R10.2). Both dynamic values are
        snapshotted once per pass (G91), and the stored-pair diff uses the one
        read-only entries query — never one HTTP GET per source (R10.3).
        """
        cross_ip = cross_values.current_cross_nginx_ip()
        resolver_name = settings.CROSS_RESOLVER_NAME
        db = SessionLocal()
        try:
            domains = service_grants.reachable_domains(db)
            changed = (
                self.write_dnsmasq_config(domains, cross_nginx_ip=cross_ip)
                if cross_ip else False
            )
            sources = service_grants.sources_with_targets(db)
            entries = service_grants.entries_by_id()
        finally:
            db.close()
        applied = 0
        for service_id in list(sources):
            entry = entries.get(str(service_id))
            if entry is not None and (await self._sync_source(
                    entry, resolver_name=resolver_name))["ok"]:
                applied += 1
        # G95 R7 — a source that lost its LAST relationship must release the
        # pair even while it is stopped: the stored fields are cleared and the
        # container edits skip stopped containers, so a later start cannot
        # re-apply it. It is not the target's runtime state that keeps a pair.
        cleared = 0
        clear_failed = 0
        for service_id, entry in entries.items():
            if str(service_id) in sources:
                continue
            if (await self._clear_source(entry))["ok"]:
                cleared += 1 if entry.get("extra_resolver") else 0
            else:
                clear_failed += 1
        return {"domains": sorted(domains), "config_changed": changed,
                "sources": len(sources), "applied": applied,
                "failed": len(sources) - applied,
                "cleared": cleared, "clear_failed": clear_failed}

    async def sync_source(self, service_id: str) -> dict:
        """Public targeted sync: record the durable outcome, then return it.

        R12 — every completion (ok / deferred / error, including the absent
        source skip and the bounded retry) overwrites `grant_sync_state` for
        this source. The grant-sync condition reads that row, so a transient
        editor warning survives the message and a gateway restart.
        """
        result = await self._sync_source_once(service_id)
        try:
            from .alert_service import record_grant_sync_outcome
            record_grant_sync_outcome(str(service_id), result)
        except Exception as exc:  # noqa: BLE001 — the sync result is already known
            _log.warning("grant-sync outcome record failed for %s: %s",
                         service_id, exc)
        return result

    async def _sync_source_once(self, service_id: str) -> dict:
        """The TARGETED grant sync: dnsmasq + the affected source only (R10.1).

        A grant set/bulk set/remove calls this, and the request awaits the one
        maintenance task. It never sweeps the other sources: a stale one is the
        global reconciler's job (startup/address/lifecycle).
        """
        cross_ip = cross_values.current_cross_nginx_ip()
        resolver_name = settings.CROSS_RESOLVER_NAME
        db = SessionLocal()
        try:
            domains = service_grants.reachable_domains(db)
            entries = service_grants.entries_by_id()
            entry = entries.get(str(service_id))
            targets = service_grants.targets_for(db, entry) if entry else []
        finally:
            db.close()
        changed = (
            self.write_dnsmasq_config(domains, cross_nginx_ip=cross_ip)
            if cross_ip else False
        )
        result = {"service_id": str(service_id), "domains": sorted(domains),
                  "config_changed": changed, "applied": 0, "cleared": 0,
                  "outcome": OUTCOME_OK, "reason": None}
        if entry is None:
            # A tombstoned/absent source has nothing to configure. The targeted
            # fan-out (R14) can legitimately include a source that the same
            # account deletion removed; skip it rather than fail the pass.
            result.update(outcome=OUTCOME_OK,
                          reason="the source service is absent (skipped)")
            return result
        if targets:
            action = await self._sync_source(entry, resolver_name=resolver_name)
            if action["ok"]:
                result["applied"] = 1
        elif entry.get("extra_resolver"):
            # The relationship ended: clear even when the source is stopped
            # (G95 R7.4). No stored pair means there is nothing to clear.
            action = await self._clear_source(entry)
            if action["ok"]:
                result["cleared"] = 1
        else:
            action = self._outcome(True, OUTCOME_OK)
        result["outcome"] = action["outcome"]
        result["reason"] = action.get("reason")
        return result

    async def sync_sources(self, source_ids) -> dict:
        """The targeted FAN-OUT: one `sync_source` per distinct source (R14).

        Account-level ACL changes can affect several sources at once; this walks
        exactly the affected-source set, deduplicated, and never calls
        `sync_all`. Each `sync_source` rewrites the dnsmasq wildcard from the
        full grant state and submits only the source whose stored pair differs.
        An absent/tombstoned source is skipped as `ok` (the account deletion can
        remove its own services in the same request).
        """
        ids = list(dict.fromkeys(str(i) for i in (source_ids or []) if i))
        results: dict[str, dict] = {}
        failed: list[str] = []
        for service_id in ids:
            try:
                action = await self.sync_source(service_id)
            except Exception as exc:  # noqa: BLE001 — report the one source
                _log.warning("targeted fan-out for %s raised: %s", service_id, exc)
                action = self._outcome(False, OUTCOME_ERROR, str(exc))
            results[service_id] = action
            if not action.get("ok"):
                _log.info("targeted fan-out for %s ended %s: %s",
                          service_id, action.get("outcome"), action.get("reason"))
                failed.append(service_id)
        return {"sources": ids, "results": results, "failed": failed}

    async def startup_pass(self) -> dict:
        """The gateway's one-time startup pass, retried while the -api boots.

        A stack rebuild starts the gateway and the -api together; the first
        attempts may find the -api mid-migration. The stored fields make the
        -api's own startup pass sufficient for already-configured sources, so
        this retry loop is only needed for the first convergence.
        """
        last: dict = {}
        for attempt in range(1, 13):
            last = await self.sync_all()
            if last.get("failed", 0) == 0 and last.get("clear_failed", 0) == 0:
                return last
            _log.info("cross startup pass attempt %d: %s failed, %s clear-failed; retrying",
                      attempt, last.get("failed"), last.get("clear_failed"))
            await asyncio.sleep(10.0)
        return last

    async def _refresh_dnsmasq(self, cross_nginx_ip: str) -> None:
        """Rewrite the resolver records from the grant state and the new address."""
        db = SessionLocal()
        try:
            domains = service_grants.reachable_domains(db)
        finally:
            db.close()
        self.write_dnsmasq_config(domains, cross_nginx_ip=cross_nginx_ip)

    async def watch_loop(self) -> None:
        """The ~5 s resolve that owns both dynamic values (GRILLING G91).

        One worker runs it (the lease); every tick re-resolves the cross nginx
        alias and the resolver name. A cross-nginx change rewrites the dnsmasq
        records (the trust check already reads the same current value); a
        resolver change triggers the full re-apply pass. Nothing else watches:
        the `-api` stays a writer and has no detection role.
        """
        from .loop_lease import acquire_lease

        interval = max(1.0, settings.CROSS_WATCH_INTERVAL_SEC)
        while True:
            try:
                if acquire_lease("cross_watch", max(30.0, interval * 3)):
                    result = await asyncio.to_thread(cross_values.refresh)
                    if result["cross_nginx_changed"]:
                        _log.info("cross nginx address changed to %s",
                                  result["cross_nginx_ip"])
                        await self._refresh_dnsmasq(result["cross_nginx_ip"])
                    # G101/R4.2 — the proxy resolves the cross resolver by
                    # container NAME; a resolver IP change no longer re-applies
                    # the pair, so the resolver-change branch is retired.
            except Exception:  # noqa: BLE001 — the next tick retries
                _log.exception("cross-path address watch failed")
            await asyncio.sleep(interval)

    def schedule_retry_sync(self, source_ids, *, delay_s: float = 10.0,
                            max_attempts: int = 6) -> None:
        """Background retry after a failed TARGETED sync (R4/R13/R14).

        The retry repeats the targeted fan-out over exactly the affected
        sources (R13's deployed source, R14's affected-source set); it never
        sweeps the stack. S15 settled this scope, and the old no-source global
        branch is removed so a future caller cannot reintroduce a stack-wide
        sweep. The bounded exponential backoff stops when the pass converges.
        """
        ids = list(dict.fromkeys(str(i) for i in (source_ids or []) if i))
        if not ids:
            _log.warning("schedule_retry_sync called without a source; ignored")
            return
        try:
            loop = asyncio.get_running_loop()
        except RuntimeError:
            return
        loop.create_task(self._retry_sync(delay_s, max_attempts, ids))

    async def _retry_sync(self, delay_s: float, max_attempts: int,
                          source_ids: list[str]) -> None:
        delay = max(1.0, delay_s)
        for attempt in range(1, max_attempts + 1):
            await asyncio.sleep(delay)
            try:
                result = await self.sync_sources(source_ids)
                done = not result.get("failed")
            except Exception:  # noqa: BLE001 — the next attempt retries
                _log.exception("cross-path retry pass failed")
                done = False
                result = {}
            if done:
                _log.info("cross-path retry pass converged on attempt %d", attempt)
                return
            _log.info(
                "cross-path retry pass attempt %d still has %s failed "
                "source(s) of %s", attempt, len(result.get("failed") or []),
                len(source_ids))
            delay = min(delay * 2.0, 60.0)

    async def sync_after_task(self, task_id: str, on_settled=None) -> None:
        """Wait for a deploy/rebuild/remove task to finish, then refresh everything.

        Reads the task row directly (R9.2) instead of polling the -api.
        ``on_settled`` runs after the task is terminal and BEFORE the sync pass —
        the service-delete path uses it to remove the grant rows in both
        directions (R7), so the pass sees the relationship already ended. It
        runs for a failed task too: a delete whose tombstone is written but whose
        final reload failed still ended the relationship (R3).
        """
        from . import registry_tasks
        try:
            while True:
                data = await asyncio.to_thread(registry_tasks.get, task_id) or {}
                if str(data.get("status") or "") in (
                        "completed", "failed", "cancelled", "unknown"):
                    break
                await asyncio.sleep(2.0)
        except Exception:  # noqa: BLE001 — the next change/startup retries
            return
        if on_settled is not None:
            try:
                on_settled()
            except Exception:  # noqa: BLE001 — the sync pass still runs
                _log.exception("post-task hook failed for %s", task_id)
        await self.sync_all()


cross_orchestrator = CrossOrchestrator()


def _refusal_code(exc: Exception) -> str | None:
    """The -api's queue refusal code from an httpx error, if any."""
    resp = getattr(exc, "response", None)
    if resp is None:
        return None
    try:
        body = resp.json()
    except Exception:  # noqa: BLE001
        return None
    if isinstance(body, dict):
        if isinstance(body.get("error"), str):
            return body["error"]
        detail = body.get("detail")
        if isinstance(detail, dict) and isinstance(detail.get("error"), str):
            return detail["error"]
    return None


def schedule_sync(source_ids=None) -> None:
    """Fire-and-forget refresh from an ASYNC request handler.

    With ``source_ids`` it runs the targeted fan-out over exactly those sources
    (R14); with none it keeps the all-source pass.
    """
    ids = list(dict.fromkeys(str(i) for i in (source_ids or []) if i)) or None
    if source_ids is not None and not ids:
        return  # an empty affected set means nothing to refresh
    try:
        loop = asyncio.get_running_loop()
    except RuntimeError:
        return
    loop.create_task(
        cross_orchestrator.sync_sources(ids) if ids
        else cross_orchestrator.sync_all())


def schedule_sync_threadsafe(source_ids=None) -> None:
    """Fire-and-forget refresh from a SYNC route (FastAPI's threadpool).

    There is no running loop in that thread, so the refresh gets its own thread
    and its own event loop; the request reply is never delayed by the -api call.
    With ``source_ids`` the thread runs the targeted fan-out and its bounded
    retry (R14); with none it keeps the all-source pass.
    """
    import threading

    ids = list(dict.fromkeys(str(i) for i in (source_ids or []) if i)) or None
    if source_ids is not None and not ids:
        return  # an empty affected set means nothing to refresh

    def _run() -> None:
        if not ids:
            try:
                asyncio.run(cross_orchestrator.sync_all())
            except Exception:  # noqa: BLE001 — the next change/startup retries
                _log.exception("cross-path refresh failed")
            return
        remaining = ids
        delay = 10.0
        for attempt in range(1, 7):
            try:
                result = asyncio.run(cross_orchestrator.sync_sources(remaining))
                remaining = result.get("failed") or []
            except Exception:  # noqa: BLE001 — the next attempt retries
                _log.exception("targeted cross-path fan-out failed")
            if not remaining:
                return
            _log.info(
                "targeted fan-out attempt %d still has %d failed source(s)",
                attempt, len(remaining))
            time.sleep(delay)
            delay = min(delay * 2.0, 60.0)

    threading.Thread(target=_run, name="cross-sync-targeted", daemon=True).start()
